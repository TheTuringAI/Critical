import { StrictMode, useEffect, useState } from "react";
import { createRoot } from "react-dom/client";
import { DEFAULT_BACKEND_URL, getBackendUrl, setBackendUrl } from "../shared/settings";
import "./options.css";

function Options() {
  const [url, setUrl] = useState("");
  const [status, setStatus] = useState<string>("");

  useEffect(() => {
    getBackendUrl().then(setUrl);
  }, []);

  const save = async () => {
    let origin: string;
    try {
      origin = new URL(url).origin;
    } catch {
      setStatus("Enter a valid URL, e.g. https://context.example.org");
      return;
    }
    const granted = await chrome.permissions.request({ origins: [origin + "/*"] }).catch(() => false);
    if (!granted && !/^http:\/\/(localhost|127\.0\.0\.1):8000$/.test(origin)) {
      setStatus("Permission to contact this server was denied.");
      return;
    }
    await setBackendUrl(url);
    try {
      const health = await (await fetch(origin + new URL(url).pathname.replace(/\/+$/, "") + "/healthz")).json();
      setStatus(health.configured ? "Saved. Server is reachable and configured." : "Saved. Server is reachable but missing API keys.");
    } catch {
      setStatus("Saved, but the server could not be reached.");
    }
  };

  return (
    <main className="mx-auto max-w-[560px] p-8 font-sans text-base text-neutral-900">
      <h1 className="m-0 text-lg font-bold">Video Context Overlay</h1>
      <p className="text-sm text-neutral-600">
        Notes are generated by a stateless verification server. Only the YouTube video ID is sent; no account, history
        or transcript is stored.
      </p>
      <label className="mt-4 block text-sm font-medium" htmlFor="backend">
        Verification server URL
      </label>
      <div className="mt-1 flex gap-2">
        <input
          id="backend"
          value={url}
          placeholder={DEFAULT_BACKEND_URL}
          onChange={(event) => setUrl(event.target.value)}
          className="flex-1 rounded border border-solid border-neutral-300 px-2 py-1.5 text-base"
        />
        <button type="button" onClick={save} className="cursor-pointer rounded border-0 bg-blue-600 px-4 text-base text-white">
          Save
        </button>
      </div>
      {status && <p className="mt-2 text-sm">{status}</p>}
    </main>
  );
}

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <Options />
  </StrictMode>,
);
